# colour-blind-safe palette (Okabe-Ito)
C = {
    "blue": "#0072B2", "orange": "#E69F00", "green": "#009E73", "red": "#D55E00",
    "purple": "#CC79A7", "sky": "#56B4E9", "yellow": "#F0E442", "black": "#000000",
    "grey": "#7f7f7f",
}

_MACROS: dict[str, str] = {}


def macro(name: str, value, fmt: str | None = None) -> str:
    """Register a number for the paper as \\name (letters only)."""
    if not name.isalpha():
        raise ValueError(f"LaTeX macro names must be letters only: {name}")
    text = format(value, fmt) if fmt else str(value)
    _MACROS[name] = text
    return text


def write_macros() -> None:
    lines = ["% AUTO-GENERATED by experiments/run_all.py -- do not edit by hand"]
    for k in sorted(_MACROS):
        lines.append(f"\\newcommand{{\\{k}}}{{{_MACROS[k]}}}")
    (GENERATED / "numbers.tex").write_text("\n".join(lines) + "\n")
    (RESULTS / "numbers.json").write_text(json.dumps(_MACROS, indent=2, sort_keys=True))


def save_fig(fig, name: str) -> None:
    fig.savefig(FIGURES / f"{name}.pdf", bbox_inches="tight")
    fig.savefig(FIGURES / f"{name}.png", bbox_inches="tight")
    plt.close(fig)


def write_table(name: str, body: str) -> None:
    (GENERATED / f"{name}.tex").write_text("% AUTO-GENERATED -- do not edit by hand\n" + body)


def sci(x: float, digits: int = 1) -> str:
    """Scientific notation for use inside LaTeX math mode, e.g. 3.1\\times10^{-5}."""
    if x == 0:
        return "0"
    m, e = f"{x:.{digits}e}".split("e")
    return rf"{m}\times10^{{{int(e)}}}"

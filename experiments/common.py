ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
FIGURES = ROOT / "paper" / "figures"
GENERATED = ROOT / "paper" / "generated"
for d in (RESULTS, FIGURES, GENERATED):
    d.mkdir(parents=True, exist_ok=True)

